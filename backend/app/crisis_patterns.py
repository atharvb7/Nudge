"""Canonical crisis-language patterns — the single source of truth.

`backend/app/safety.py` uses these directly, and `backend/scripts/sync_crisis_ts.py`
writes the very same regexes into `shared/src/crisis.ts` (the on-device check),
so the two layers can never drift. `tests/test_crisis_sync.py` fails if they do.

Rules for editing:
* Text is normalised before matching: curly quotes → straight, then ALL
  apostrophes are deleted ("don't" → "dont", "I'm" → "im", "isn't" → "isnt"),
  whitespace collapsed, idioms removed. Write patterns for apostrophe-free text.
* Patterns must be valid in both Python `re` and JavaScript (no `(?P<…>)`, no
  inline flags, no possessive quantifiers). Matching is case-insensitive.
* Err toward care. Explicit or method/intent language → HIGH. Ambiguous or
  hopeless language → CONCERN, whose screen offers "I'm safe — just frustrated".
"""

