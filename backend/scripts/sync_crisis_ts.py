"""Write the canonical crisis patterns into shared/src/crisis.ts (the on-device check).

    cd backend && python scripts/sync_crisis_ts.py          # rewrite the generated block
    cd backend && python scripts/sync_crisis_ts.py --check  # exit 1 if out of date

Only the block between the GENERATED markers is replaced; resources and copy
below it are hand-written.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from app import crisis_patterns as P  # noqa: E402

TS = ROOT / "shared" / "src" / "crisis.ts"
BEGIN = "// <GENERATED by backend/scripts/sync_crisis_ts.py — edit backend/app/crisis_patterns.py instead>"
END = "// </GENERATED>"


def js_regex(src: str, flags: str) -> str:
    return "/" + src.replace("/", r"\/") + "/" + flags


def block() -> str:
    def arr(name: str, items: list[str], flags: str) -> str:
        body = "\n".join(f"  {js_regex(x, flags)}," for x in items)
        return f"const {name}: RegExp[] = [\n{body}\n];"

    lines = [
        BEGIN,
        arr("IDIOMS", P.IDIOMS, "gi"),
        "",
        arr("HIGH_RISK", P.HIGH, "i"),
        "",
        arr("HOPELESSNESS", P.CONCERN, "i"),
        "",
        f"const NEGATABLE = {js_regex(P.NEGATABLE, 'i')};",
        f"const NEGATION_BEFORE = {js_regex(P.NEGATION_BEFORE, 'i')};",
        f"const CONCEPT_SELF = {js_regex(P.CONCEPT_SELF, 'i')};",
        f"const CONCEPT_DEATH = {js_regex(P.CONCEPT_DEATH, 'i')};",
        f"const CONCEPT_INTENT = {js_regex(P.CONCEPT_INTENT, 'i')};",
        f"const CONCEPT_EXCLUDE = {js_regex(P.CONCEPT_EXCLUDE, 'i')};",
        f"const LEMMAS: Record<string, string> = {json.dumps(P.LEMMAS, ensure_ascii=False)};",
        END,
    ]
    return "\n".join(lines)


def render(current: str) -> str:
    start, end = current.index(BEGIN), current.index(END) + len(END)
    return current[:start] + block() + current[end:]


if __name__ == "__main__":
    cur = TS.read_text(encoding="utf8")
    new = render(cur)
    if "--check" in sys.argv:
        sys.exit(0 if new == cur else 1)
    TS.write_text(new, encoding="utf8")
    print(f"wrote {TS.relative_to(ROOT)}")
