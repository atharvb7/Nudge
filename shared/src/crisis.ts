export type CrisisLevel = 'none' | 'concern' | 'high';

/** Same steps as _normalise() in backend/app/safety.py — keep them identical. */
function normalise(text: string): string {
  let t = text.replace(/[’‘`]/g, "'").replace(/'/g, '').replace(/\s+/g, ' ').trim();
  for (const r of IDIOMS) t = t.replace(r, ' ');
  t = t.replace(/\b\w+\b/g, (w) => LEMMAS[w.toLowerCase()] ?? w);
  return t.replace(/\s+/g, ' ').trim();
}

function hit(patterns: RegExp[], t: string, allowNegation: boolean): boolean {
  return patterns.some((r) => {
    const g = new RegExp(r.source, r.flags.includes('g') ? r.flags : r.flags + 'g');
    for (const m of t.matchAll(g)) {
      const at = m.index ?? 0;
      if (allowNegation && NEGATABLE.test(m[0]) && NEGATION_BEFORE.test(t.slice(Math.max(0, at - 24), at))) continue;
      return true;
    }
    return false;
  });
}

const SENTENCE_SPLIT = /[.!?;\n]+|,\s+(?:but|and|so)\s+/i;

/** First person + death/ending concept + intent/despair in one sentence. */
function conceptHit(t: string): boolean {
  for (const sent of t.split(SENTENCE_SPLIT)) {
    if (CONCEPT_EXCLUDE.test(sent)) continue;
    const d = CONCEPT_DEATH.exec(sent);
    if (!d || !CONCEPT_SELF.test(sent) || !CONCEPT_INTENT.test(sent)) continue;
    // "i dont want to die" / "im not suicidal" is reassurance, not risk
    if (/^(?:die|dying|dead|suicid)/i.test(d[0]) && NEGATION_BEFORE.test(sent.slice(0, d.index))) continue;
    return true;
  }
  return false;
}

export function detectCrisis(text: string | null | undefined): CrisisLevel {
  if (!text) return 'none';
  const t = normalise(text);
  if (!t) return 'none';
  if (hit(HIGH_RISK, t, true)) return 'high';
  if (hit(HOPELESSNESS, t, false) || conceptHit(t)) return 'concern';
  return 'none';
}

